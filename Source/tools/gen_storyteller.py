"""Generates the Hell Unbound storyteller from the game's own Cassandra Classic.

Usage:  python3 Source/tools/gen_storyteller.py "<RimWorld>/Data"

Copies Cassandra's comps verbatim (so it tracks vanilla after a game update) and adds a demon wave
cycle: HP_DemonWave, a raid that is always demons. Writes Mods/Biotech/Defs/HP_Storyteller.xml.
Re-run after a RimWorld update. Never hand-edit the output.
"""
import copy
import os
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "Mods", "Biotech", "Defs", "HP_Storyteller.xml")

DEMON_WAVES = """<li Class="StorytellerCompProperties_OnOffCycle">
  <incident>HP_DemonWave</incident>
  <minDaysPassed>15</minDaysPassed>
  <onDays>3</onDays>
  <offDays>9</offDays>
  <minSpacingDays>4</minSpacingDays>
  <numIncidentsRange>1~1</numIncidentsRange>
</li>"""


def main(data):
    path = os.path.join(data, "Core", "Defs", "Storyteller", "Storytellers.xml")
    root = ET.parse(path).getroot()
    cass = next(d for d in root.iter("StorytellerDef") if d.findtext("defName") == "Cassandra")
    st = ET.Element("StorytellerDef")
    for tag, text in [
        ("defName", "HP_HellUnbound"),
        ("label", "Hell Unbound"),
        ("description", "Cassandra's classic rising curve, with the hell gates thrown open: every couple of weeks a wave of demons comes for the colony's souls, on top of everything else."),
        ("portraitLarge", "UI/HeroArt/HP_HellUnbound"),
        ("portraitTiny", "UI/HeroArt/HP_HellUnboundTiny"),
        ("listOrder", "25"),
    ]:
        ET.SubElement(st, tag).text = text
    comps = copy.deepcopy(cass.find("comps"))
    comps.append(ET.fromstring(DEMON_WAVES))
    st.append(comps)
    ET.indent(st, space="  ", level=1)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<Defs>\n\n')
        f.write("  <!-- GENERATED by Source/tools/gen_storyteller.py from the game's Cassandra Classic. Re-run it, don't hand-edit. -->\n")
        f.write("  " + ET.tostring(st, encoding="unicode") + "\n\n</Defs>\n")
    print("wrote", os.path.relpath(OUT, ROOT), "with", len(comps), "comps")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
